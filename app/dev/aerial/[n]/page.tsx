'use client';
import { useParams } from 'next/navigation';
import { AerialLot, treesFor } from '@/components/illustrations/AerialLot';
import { sampleFrame, sampleParcel, SAMPLE_H, SAMPLE_W } from '@/components/scan/samples';
import type { ScanPolygon } from '@/lib/scanMath';
import type { Pt, Rect } from '@/lib/geometry';
import { palette as P, shade, seeded } from '@/lib/illustrationPalette';

/**
 * Dev-only render target for the bundled sample aerials. Screenshot at 1200×900 with
 * `node scripts/dev/shot.mjs http://localhost:3100/dev/aerial/1 public/samples/aerial-1.png light 1200 900 1500`.
 * The page also embeds the matching fixture JSON (building, parking, open land, trees, access) in a
 * <script type="application/json"> so the fixture is generated by the same code that draws the image.
 */

/** Open-land rectangles per sample, in the lot's normalized frame (hand-placed around the building and parking). */
const OPEN_RECTS: Record<number, Rect[]> = {
  1: [{ x: 0.03, y: 0.38, w: 0.94, h: 0.31 }],
  2: [{ x: 0.04, y: 0.06, w: 0.76, h: 0.4 }, { x: 0.84, y: 0.2, w: 0.13, h: 0.26 }],
  3: [{ x: 0.03, y: 0.52, w: 0.49, h: 0.35 }, { x: 0.38, y: 0.08, w: 0.0, h: 0.0 }].filter((r) => r.w > 0),
};

/** Neighbouring rooftops, trees and sidewalks outside the lot so the sample reads as a real aerial. */
function Surroundings({ n, streetSide, frame, scale, lot }: { n: number; streetSide: string; frame: Rect; scale: number; lot: Rect }) {
  const rnd = seeded(11 + n);
  const houses: { x: number; y: number; w: number; h: number; tone: number; rot: number }[] = [];
  const trees: { x: number; y: number; r: number; kind: number }[] = [];
  // Street band in image px, same geometry AerialLot uses (0.14 units wide, 0.02 off the lot edge).
  const street: Rect = streetSide === 'top' ? { x: 0, y: lot.y - 0.16 * scale, w: SAMPLE_W, h: 0.14 * scale }
    : streetSide === 'bottom' ? { x: 0, y: lot.y + lot.h + 0.02 * scale, w: SAMPLE_W, h: 0.14 * scale }
    : streetSide === 'left' ? { x: lot.x - 0.16 * scale, y: 0, w: 0.14 * scale, h: SAMPLE_H } : { x: lot.x + lot.w + 0.02 * scale, y: 0, w: 0.14 * scale, h: SAMPLE_H };
  const horizontal = street.w > street.h;
  const keepOut = [{ x: lot.x - 0.05 * scale, y: lot.y - 0.05 * scale, w: lot.w + 0.1 * scale, h: lot.h + 0.1 * scale }, { x: street.x - 14, y: street.y - 14, w: street.w + 28, h: street.h + 28 }];
  const hits = (r: Rect, pad = 0) => keepOut.some((b) => r.x < b.x + b.w + pad && r.x + r.w + pad > b.x && r.y < b.y + b.h + pad && r.y + r.h + pad > b.y);
  for (let i = 0; i < 600 && houses.length < 16; i++) {
    const w = 64 + rnd() * 50, h = 54 + rnd() * 40;
    const x = rnd() * (SAMPLE_W - w), y = rnd() * (SAMPLE_H - h);
    const r = { x, y, w, h };
    if (hits(r, 10)) continue;
    if (houses.some((o) => r.x < o.x + o.w + 26 && r.x + r.w + 26 > o.x && r.y < o.y + o.h + 26 && r.y + r.h + 26 > o.y)) continue;
    houses.push({ x, y, w, h, tone: Math.floor(rnd() * 3), rot: (rnd() - 0.5) * 4 });
  }
  for (let i = 0; i < 800 && trees.length < 30; i++) {
    const r = 12 + rnd() * 18;
    const x = r + rnd() * (SAMPLE_W - 2 * r), y = r + rnd() * (SAMPLE_H - 2 * r);
    const box = { x: x - r, y: y - r, w: 2 * r, h: 2 * r };
    if (hits(box, -6)) continue;
    if (houses.some((o) => box.x < o.x + o.w + 6 && box.x + box.w + 6 > o.x && box.y < o.y + o.h + 6 && box.y + box.h + 6 > o.y)) continue;
    if (trees.some((t) => Math.hypot(t.x - x, t.y - y) < t.r + r + 4)) continue;
    trees.push({ x, y, r, kind: Math.floor(rnd() * 3) });
  }
  const dashes: Rect[] = [];
  if (horizontal) {
    for (let i = -12; i < 40; i++) {
      const x = frame.x + i * 0.11 * scale, w = 0.06 * scale;
      if (x + w > frame.x && x < frame.x + frame.w) continue;
      dashes.push({ x, y: street.y + street.h / 2 - 0.003 * scale, w, h: 0.006 * scale });
    }
  }
  // Same position AerialLot uses for its own sidewalk so the two segments join seamlessly.
  const sidewalkY = streetSide === 'top' ? street.y + street.h - 0.012 * scale : street.y - 0.012 * scale;
  const roofs = [P.roof, P.roofTerracotta, P.wallClayShade];
  const roofsLight = [P.roofLight, P.roofTerracottaLight, P.wallClay];
  return (
    <svg width={SAMPLE_W} height={SAMPLE_H} viewBox={`0 0 ${SAMPLE_W} ${SAMPLE_H}`} style={{ position: 'absolute', inset: 0 }} aria-hidden>
      <defs>
        <pattern id={`ctx-grass-${n}`} width="16" height="16" patternUnits="userSpaceOnUse">
          <rect width="16" height="16" fill="#C9D7CC" />
          <circle cx="5" cy="6" r="1.3" fill={P.lawnShade} opacity="0.28" />
          <circle cx="12" cy="13" r="1.1" fill={P.lawnDeep} opacity="0.18" />
        </pattern>
      </defs>
      <rect width={SAMPLE_W} height={SAMPLE_H} fill={`url(#ctx-grass-${n})`} />
      {/* the main street continues across the whole image; AerialLot draws its own segment on top in the same tones */}
      <rect x={street.x} y={street.y} width={street.w} height={street.h} fill={P.asphalt} />
      {horizontal && <rect x={0} y={sidewalkY} width={SAMPLE_W} height={0.012 * scale} fill={P.sidewalk} />}
      {dashes.map((d, i) => <rect key={i} x={d.x} y={d.y} width={d.w} height={d.h} fill={P.paint} opacity={0.7} />)}
      {/* a quiet side street along the left edge */}
      {streetSide !== 'left' && <rect x={0} y={0} width={30} height={SAMPLE_H} fill={P.asphalt} opacity={0.9} />}
      {streetSide !== 'left' && <rect x={30} y={0} width={7} height={SAMPLE_H} fill={P.sidewalk} />}
      {houses.map((hs, i) => (
        <g key={i} transform={`rotate(${hs.rot} ${hs.x + hs.w / 2} ${hs.y + hs.h / 2})`}>
          <rect x={hs.x + 8} y={hs.y + 10} width={hs.w} height={hs.h} rx={2} fill={P.shadow} opacity={0.7} />
          <rect x={hs.x} y={hs.y} width={hs.w} height={hs.h} rx={1.5} fill={P.wallShade} />
          {/* hip roof: lit top-left planes, shaded right/bottom planes */}
          <path d={`M${hs.x} ${hs.y} L${hs.x + hs.w} ${hs.y} L${hs.x + hs.w / 2} ${hs.y + hs.h / 2} Z`} fill={roofsLight[hs.tone]} />
          <path d={`M${hs.x} ${hs.y} L${hs.x} ${hs.y + hs.h} L${hs.x + hs.w / 2} ${hs.y + hs.h / 2} Z`} fill={roofs[hs.tone]} />
          <path d={`M${hs.x + hs.w} ${hs.y} L${hs.x + hs.w} ${hs.y + hs.h} L${hs.x + hs.w / 2} ${hs.y + hs.h / 2} Z`} fill={shade(roofs[hs.tone], 0.18)} />
          <path d={`M${hs.x} ${hs.y + hs.h} L${hs.x + hs.w} ${hs.y + hs.h} L${hs.x + hs.w / 2} ${hs.y + hs.h / 2} Z`} fill={shade(roofs[hs.tone], 0.3)} />
          <rect x={hs.x + hs.w - 18} y={hs.y + 8} width={7} height={7} fill={P.wallDeep} />
          <rect x={hs.x - 6} y={hs.y + hs.h * 0.3} width={6} height={hs.h * 0.35} fill={P.sidewalk} opacity={0.8} />
        </g>
      ))}
      {trees.map((t, i) => (
        <g key={i}>
          <circle cx={t.x + 5} cy={t.y + 6} r={t.r} fill={P.shadow} opacity={0.55} />
          <circle cx={t.x} cy={t.y} r={t.r} fill={t.kind === 1 ? P.jacaranda : P.tree} />
          <circle cx={t.x - t.r * 0.3} cy={t.y - t.r * 0.3} r={t.r * 0.55} fill={t.kind === 1 ? P.jacarandaLight : P.treeLight} />
        </g>
      ))}
    </svg>
  );
}

const octagon = (cx: number, cy: number, r: number, aspect: number): Pt[] =>
  Array.from({ length: 8 }).map((_, i) => {
    const a = (i / 8) * Math.PI * 2;
    return { x: cx + Math.cos(a) * r, y: cy + Math.sin(a) * r * aspect };
  });

export default function Page() {
  const raw = useParams<{ n: string }>()?.n;
  const n = Math.min(3, Math.max(1, Number(raw) || 1));
  const parcel = sampleParcel(n);
  const f = sampleFrame(parcel);
  const b = parcel.buildingRect;

  const polygons: ScanPolygon[] = [];
  polygons.push({ id: 'building-1', category: 'building', points: f.rectToImage(b), confidence: 0.94, label: 'Sanctuary' });
  parcel.parkingRects.forEach((r, i) => polygons.push({ id: `parking-${i + 1}`, category: 'parking', points: f.rectToImage(r), confidence: 0.9, label: 'Parking lot' }));
  (OPEN_RECTS[n] ?? []).forEach((r, i) => polygons.push({ id: `open-${i + 1}`, category: 'open', points: f.rectToImage(r), confidence: 0.78, label: 'Lawn' }));
  treesFor(parcel).slice(0, 5).forEach((t, i) => polygons.push({
    id: `trees-${i + 1}`, category: 'trees', confidence: 0.7,
    points: octagon(t.x, t.y, t.r, 1).map(f.toImage),
  }));
  // Access: the footpath from the street to the building (same geometry as AerialLot draws)
  const top = parcel.streetSide === 'top';
  const access: Rect = { x: b.x + b.w / 2 - 0.02, y: top ? 0 : b.y + b.h, w: 0.04, h: top ? b.y : f.by - b.y - b.h };
  polygons.push({ id: 'access-1', category: 'access', points: f.rectToImage(access), confidence: 0.72, label: 'Entry path' });
  const fixture = { polygons, notes: `Illustrated sample lot ${n}; fixture generated from the drawing geometry.` };

  return (
    <div style={{ position: 'fixed', inset: 0, zIndex: 100, background: '#C9D7CC', overflow: 'hidden' }}>
      <style>{'nextjs-portal{display:none}'}</style>
      <Surroundings n={n} streetSide={parcel.streetSide} frame={{ x: f.ox, y: f.oy, w: f.w, h: f.h }} scale={f.scale} lot={{ x: f.ox + 0.2 * f.scale, y: f.oy + 0.2 * f.scale, w: f.bx * f.scale, h: f.by * f.scale }} />
      <div style={{ position: 'absolute', left: f.ox, top: f.oy, width: f.w, height: f.h }}>
        <AerialLot parcel={parcel} size={420} id={`sample-${n}`} groundFill="none" />
      </div>
      <div style={{
        position: 'absolute', left: 20, bottom: 20, zIndex: 2, padding: '6px 10px', borderRadius: 8,
        background: 'rgba(24,36,32,0.78)', color: '#F6F7F5', fontFamily: 'var(--font-public-sans), system-ui, sans-serif',
        fontSize: 15, lineHeight: '20px', letterSpacing: 0,
      }}>
        Sample aerial (illustrated, fictional)
      </div>
      <script id="scan-fixture" type="application/json" dangerouslySetInnerHTML={{ __html: JSON.stringify(fixture) }} />
      <span style={{ display: 'none' }} data-size={`${SAMPLE_W}x${SAMPLE_H}`} />
    </div>
  );
}
