import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:3200/scan');
await page.locator('[data-testid=sample-1]').click();
await page.getByRole('button', { name: /Scan lot/i }).click();
await page.locator('[data-polygon]').first().waitFor();
await page.waitForTimeout(2500);
const b = page.locator('[data-testid=scan-buildable]');
console.log('before', await b.getAttribute('data-value'));
const hs = page.locator('[data-vertex="open"], [data-vertex="parking"]');
console.log('handles', await hs.count());
const h = hs.first();
const box = await h.boundingBox();
console.log('box', box);
await page.mouse.move(box.x + box.width/2, box.y + box.height/2);
await page.mouse.down();
for (let i=1;i<=8;i++) await page.mouse.move(box.x + box.width/2 + i*10, box.y + box.height/2 + i*10);
await page.mouse.up();
await page.waitForTimeout(600);
console.log('after', await b.getAttribute('data-value'));
console.log('box2', await h.boundingBox());
await browser.close();
