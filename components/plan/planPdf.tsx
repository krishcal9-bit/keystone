import { pdf, Document, Page, Text, View, Image, StyleSheet } from '@react-pdf/renderer';
import type { PlanModel } from '@/lib/planModel';
import { SB4_FACTS } from '@/lib/sb4Facts';

const s = StyleSheet.create({
  page: { padding: 40, fontFamily: 'Helvetica', color: '#182420', fontSize: 11 },
  h1: { fontSize: 22, marginBottom: 2 },
  sub: { fontSize: 11, color: '#4A5753', marginBottom: 14 },
  img: { width: '100%', height: 300, objectFit: 'cover', borderRadius: 6, marginBottom: 14 },
  row: { flexDirection: 'row', gap: 18, marginBottom: 14 },
  stat: { flex: 1, borderTop: '1px solid #DDE3DF', paddingTop: 6 },
  big: { fontSize: 20, fontFamily: 'Helvetica-Bold' },
  lab: { fontSize: 9, color: '#4A5753' },
  h2: { fontSize: 12, fontFamily: 'Helvetica-Bold', marginTop: 6, marginBottom: 4 },
  p: { lineHeight: 1.4, marginBottom: 3 },
  note: { fontSize: 9, color: '#4A5753', marginTop: 16, borderTop: '1px solid #DDE3DF', paddingTop: 6 },
});

export async function buildPlanPdf({ model, png, notLegal }: { model: PlanModel; png?: string; notLegal: string }): Promise<Blob> {
  const p = model.parcel;
  const doc = (
    <Document title={`Keystone plan · ${p.displayName}`}>
      <Page size="LETTER" style={s.page}>
        <Text style={s.h1}>{p.displayName}</Text>
        <Text style={s.sub}>{p.city}, Orange County · Keystone site plan · Sample data</Text>
        {/* eslint-disable-next-line jsx-a11y/alt-text */}
        {png && <Image src={png} style={s.img} />}
        <View style={s.row}>
          <View style={s.stat}><Text style={s.big}>{model.placed}</Text><Text style={s.lab}>Habitat homes placed ({model.opts.unitType === 'flat' ? 'stacked flats' : 'townhomes'})</Text></View>
          <View style={s.stat}><Text style={s.big}>{model.minimumUnits}</Text><Text style={s.lab}>SB 4 minimum units ({model.capacity.density}/acre)</Text></View>
          <View style={s.stat}><Text style={s.big}>{model.buildable.acres.toFixed(2)}</Text><Text style={s.lab}>Buildable acres keeping {model.buildable.keptSpaces} spaces</Text></View>
          <View style={s.stat}><Text style={s.big}>{model.people}</Text><Text style={s.lab}>People housed</Text></View>
        </View>
        <Text style={s.p}>{model.meetsMinimum ? 'This layout meets the SB 4 minimum density.' : `This layout is ${model.shortfall} homes short of the SB 4 minimum; stacked flats on part of the site would close the gap.`} The congregation keeps its sanctuary, {model.buildable.keptSpaces} parking spaces and control of the land.</Text>
        <Text style={s.h2}>SB 4 in brief</Text>
        {SB4_FACTS.slice(0, 6).map((f) => <Text key={f.id} style={s.p}>• {f.text}</Text>)}
        <Text style={s.note}>{notLegal} All parcels are fictional sample data. Generated by Keystone for Habitat for Humanity of Orange County.</Text>
      </Page>
    </Document>
  );
  return pdf(doc).toBlob();
}
